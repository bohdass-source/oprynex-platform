const locale: Record<UiLanguage, string> = { de: "de-DE", ru: "ru-RU", en: "en-GB" };

type I18n = {
  lang: UiLanguage;
  setLang: (lang: UiLanguage) => void;
  t: (key: DictKey) => string;
  formatDateTime: (iso: string) => string;
  formatDate: (isoDay: string) => string;
  formatShort: (date: Date, unit: "day" | "month") => string;
  languageName: (code: string) => string;
};

const I18nContext = createContext<I18n | null>(null);

export function makeI18n(lang: UiLanguage, setLang: (lang: UiLanguage) => void = () => {}): I18n {
  return {
    lang,
    setLang,
    t: (key) => dict[key][lang],
    formatDateTime: (iso) => new Intl.DateTimeFormat(locale[lang], { dateStyle: "medium", timeStyle: "short" }).format(new Date(iso)),
    formatShort: (date, unit) => new Intl.DateTimeFormat(locale[lang], unit === "day" ? { day: "numeric", month: "short" } : { month: "short" }).format(date),
    formatDate: (isoDay) => new Intl.DateTimeFormat(locale[lang], { dateStyle: "medium", timeZone: "UTC" }).format(new Date(`${isoDay}T00:00:00Z`)),
    languageName: (code) => {
      try { return new Intl.DisplayNames([locale[lang]], { type: "language" }).of(code) ?? code; } catch { return code; }
    },
  };
}

/** German first on every device; a chosen language is remembered in this browser. */
export function I18nProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<UiLanguage>("de");
  useEffect(() => {
    try {
      const saved = localStorage.getItem(STORAGE_KEY);
      if (saved && (UI_LANGUAGES as readonly string[]).includes(saved)) setLangState(saved as UiLanguage);
    } catch { /* storage blocked: stay German */ }
  }, []);
  useEffect(() => { document.documentElement.lang = lang; }, [lang]);
  const setLang = (next: UiLanguage) => {
    setLangState(next);
    try { localStorage.setItem(STORAGE_KEY, next); } catch { /* ignore */ }
  };
  return <I18nContext.Provider value={makeI18n(lang, setLang)}>{children}</I18nContext.Provider>;
}

export function useI18n(): I18n {
  const value = useContext(I18nContext);
  if (!value) throw new Error("useI18n outside I18nProvider");
  return value;
}

