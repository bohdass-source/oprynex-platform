// Turns src/widget/widget.js and src/widget/form.js into a TypeScript string module the Worker serves at /widget.js and
// /form.js (src/widget.gen.ts, not committed).
import { readFileSync, writeFileSync } from "node:fs";

const read = (name: string) => readFileSync(new URL(`../src/widget/${name}`, import.meta.url), "utf8");
writeFileSync(new URL("../src/widget.gen.ts", import.meta.url), `// Generated by scripts/build-widget.ts from src/widget/. Do not edit.
export const WIDGET_JS = ${JSON.stringify(read("widget.js"))};
export const FORM_JS = ${JSON.stringify(read("form.js"))};
`);
